-- Удаление факта было физическим (`DELETE FROM memory_items`): ошибка агента означала безвозвратную
-- потерю, причём без следа о том, что именно исчезло — в audit_events писались только scope и kind.
-- История правок отдельного механизма не требует: правка уже создаёт новую строку и помечает старую
-- `claim_status = 'superseded'`, поэтому прежнее значение сохраняется.
--
-- Базовая таблица переименована, а под прежним именем оставлено представление с фильтром. Так все
-- существующие чтения — включая векторный поиск, который джойнит чанки через выборку из
-- memory_items — исключают мягко удалённое по построению, а не потому что где-то дописано условие.
ALTER TABLE memory_items RENAME TO memory_items_all;

ALTER TABLE memory_items_all ADD COLUMN deleted_at timestamptz;

-- Ретенция ищет только мягко удалённые, поэтому индекс частичный.
CREATE INDEX memory_items_all_deleted
  ON memory_items_all (deleted_at)
  WHERE deleted_at IS NOT NULL;

-- `SELECT *` разворачивается в список колонок в момент создания представления. Новая колонка
-- базовой таблицы не появится здесь сама: за этим следит memory-soft-delete integration test,
-- который сравнивает наборы колонок и падает, если представление отстало.
CREATE VIEW memory_items AS
  SELECT * FROM memory_items_all WHERE deleted_at IS NULL;

-- Восстановление строки требует не только очистки deleted_at: удаление помечает заявление
-- `claim_status = 'retracted'`, чтобы существующие триггеры сняли проекции нитей и подтверждённых
-- исходов. Возврат в оборот должен вернуть и статус заявления.
