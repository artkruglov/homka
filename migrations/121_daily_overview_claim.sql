-- Обзор дня бывает один на сутки человека.
--
-- Диспетчер идёт раз в десять минут, и два тика подряд отправили бы два одинаковых обзора. Заявка
-- пишется до отправки — тем же оператором, который делает повтор невозможным, а не проверкой
-- «уже отправляли?» в коде.
CREATE UNIQUE INDEX initiative_messages_daily_overview
  ON initiative_messages(user_id, sent_on)
  WHERE kind = 'suggestion';
