-- Недельный обзор: одно добровольное письмо в воскресенье вечером про то, что накопилось.
--
-- Истории T16 и B08. Утренний обзор показывает сегодняшний день, и всё, что в него не попало,
-- живёт в списках годами: 22 сентября 2026 в проде было 27 открытых дел, из них половина без
-- срока и без плана, и никто ни разу не пересмотрел их целиком. Еженедельный пересмотр GTD это
-- ровно этот пропущенный шаг, и делать его сам человек не будет: у него нет для этого повода.
--
-- Обзор это не второй коуч и не второй напоминатель: он не советует, не считает вклад и не ведёт
-- серий. Он показывает просроченное, ожидание чужого ответа и дела без следующего шага, задаёт три
-- вопроса и выключается одной фразой. `weekly_review_enabled` NULL значит «ещё не спрашивали»:
-- приглашение остаётся работой коуча, здесь хранится только ответ человека.
ALTER TYPE initiative_kind ADD VALUE 'weekly_review';
ALTER TYPE proactive_delivery_source_kind ADD VALUE 'weekly_review';

ALTER TABLE user_notification_settings ADD COLUMN weekly_review_enabled boolean;
