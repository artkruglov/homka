-- Сфера жизни: необязательная метка записи, а не новая граница доступа.
--
-- В документе о балансе семьи шесть представлений («Для себя», «Мы вдвоём», «Семья и дети», «Дом и
-- забота»), но в коде их не было вовсе: человек видел один плоский список из двадцати семи дел.
-- Метка ставится только по словам человека, ничего не требует и прав не меняет: «Мои дела» и
-- «Когда-нибудь» остаются видами, а не метками.
ALTER TABLE shared_tasks
  ADD COLUMN life_area text CHECK (life_area IN ('self', 'couple', 'kids', 'home', 'work'));
CREATE INDEX shared_tasks_life_area ON shared_tasks(family_id, life_area)
  WHERE life_area IS NOT NULL;
