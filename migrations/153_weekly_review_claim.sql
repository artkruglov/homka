-- Обзор приходит раз в неделю человека, а не раз в десять минут. Десятиминутный тик ищет
-- воскресный вечер, и без этого индекса каждый следующий тик того же вечера слал бы второй обзор.
-- Неделя считается по `sent_on`, местной дате человека, поэтому заявка не зависит от часов сервера.
--
-- Новое значение перечисления нельзя использовать в той же транзакции, где оно добавлено, поэтому
-- индекс живёт отдельно от 152 (так же, как 146 отделена от 145).
CREATE UNIQUE INDEX initiative_messages_weekly_review_week
  ON initiative_messages(user_id, (date_trunc('week', sent_on::timestamp)::date))
  WHERE kind = 'weekly_review';
