/**
 * Каталог продуктов: адрес источника и пределы.
 *
 * Экспорт:
 * - `GROCERY_MCP_URL`, `GROCERY_AVAILABLE`: источник и признак его настройки.
 * - Пределы выдачи, корзины и ожидания ответа.
 *
 * Источник это официальный MCP-сервер ВкусВилла. Он читается без авторизации, поэтому доступа к
 * аккаунту человека у бота нет: собрать корзину можно, оформить заказ и заплатить — нет. Ссылка
 * на корзину открывается человеком, и адрес доставки он выбирает у себя в аккаунте.
 *
 * Инструмент появляется только там, где источник настроен: иначе его описание стоило бы токенов
 * на каждом шаге модели и обещало бы возможность, которой в этой установке нет.
 */
export const GROCERY_MCP_URL = process.env.GROCERY_MCP_URL ?? "";
export const GROCERY_AVAILABLE = /^https:\/\/[a-z0-9.-]+\/[\w./-]*$/iu.test(GROCERY_MCP_URL);

/** Страница источника фиксирована десятью позициями; модели столько и нужно. */
export const GROCERY_SEARCH_MAX_ITEMS = 10;
/** Предел корзины задан самим источником: больше двадцати позиций ссылка не принимает. */
export const GROCERY_CART_MAX_ITEMS = 20;
export const GROCERY_CART_MIN_QUANTITY = 0.01;
export const GROCERY_CART_MAX_QUANTITY = 40;
export const GROCERY_REQUEST_TIMEOUT_MS = 15_000;
